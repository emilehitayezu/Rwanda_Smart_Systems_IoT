alter table public.solutions enable row level security;
alter table public.team_members enable row level security;
alter table public.admin_users enable row level security;
alter table public.stories enable row level security;

drop policy if exists "Admins can read admin membership" on public.admin_users;
create policy "Admins can read admin membership"
  on public.admin_users for select
  to authenticated
  using (user_id = auth.uid());

drop policy if exists "Public can read published solutions" on public.solutions;
create policy "Public can read published solutions"
  on public.solutions for select
  to anon, authenticated
  using (is_published = true);

drop policy if exists "Public can read visible team members" on public.team_members;
create policy "Public can read visible team members"
  on public.team_members for select
  to anon, authenticated
  using (is_visible = true);

drop policy if exists "Admins can manage solutions" on public.solutions;
create policy "Admins can manage solutions"
  on public.solutions for all
  to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "Admins can manage team members" on public.team_members;
create policy "Admins can manage team members"
  on public.team_members for all
  to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "Public can read published stories" on public.stories;
create policy "Public can read published stories"
  on public.stories for select
  to anon, authenticated
  using (is_published = true);

drop policy if exists "Admins can manage stories" on public.stories;
create policy "Admins can manage stories"
  on public.stories for all
  to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "Public can view story files" on storage.objects;
create policy "Public can view story files"
  on storage.objects for select
  using (bucket_id = 'story-files');

drop policy if exists "Admins can upload story files" on storage.objects;
create policy "Admins can upload story files"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'story-files' and exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "Admins can update story files" on storage.objects;
create policy "Admins can update story files"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'story-files' and exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "Admins can delete story files" on storage.objects;
create policy "Admins can delete story files"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'story-files' and exists (select 1 from public.admin_users where user_id = auth.uid()));

