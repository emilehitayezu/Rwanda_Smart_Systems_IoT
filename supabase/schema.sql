create or replace function public.start_conversation(
  p_visitor_token text,
  p_visitor_name text,
  p_visitor_email text,
  p_body text
)
returns public.conversations
language plpgsql
security definer
set search_path = public
as $$
declare
  new_conversation public.conversations;
begin
  insert into public.conversations (visitor_token, visitor_name, visitor_email)
  values (p_visitor_token, p_visitor_name, nullif(p_visitor_email, ''))
  returning * into new_conversation;
  insert into public.conversation_messages (conversation_id, sender_type, body)
  values (new_conversation.id, 'visitor', p_body);
  insert into public.conversation_messages (conversation_id, sender_type, body)
  values (
    new_conversation.id,
    'bot',
    'Thanks for reaching out. What would you like help with: an IoT solution, a project partnership, training, or something else?'
  );
  return new_conversation;
end;
$$;

create or replace function public.get_visitor_messages(p_conversation_id bigint, p_visitor_token text)
returns setof public.conversation_messages
language sql
security definer
set search_path = public
as $$
  select m.* from public.conversation_messages m
  join public.conversations c on c.id = m.conversation_id
  where m.conversation_id = p_conversation_id and c.visitor_token = p_visitor_token
  order by m.created_at;
$$;

create or replace function public.send_visitor_message(
  p_conversation_id bigint,
  p_visitor_token text,
  p_body text
)
returns public.conversation_messages
language plpgsql
security definer
set search_path = public
as $$
declare
  new_message public.conversation_messages;
begin
  if not exists (
    select 1 from public.conversations
    where id = p_conversation_id and visitor_token = p_visitor_token and status = 'open'
  ) then
    raise exception 'Conversation not found or closed';
  end if;
  insert into public.conversation_messages (conversation_id, sender_type, body)
  values (p_conversation_id, 'visitor', p_body)
  returning * into new_message;
  update public.conversations set updated_at = now(), needs_attention = true where id = p_conversation_id;
  return new_message;
end;
$$;

